#!/usr/bin/env node
// Writes docs/db/SCHEMA_SUMMARY.md from supabase/migrations/*.sql so the graphify graph can see the DB layer.
// ponytail: regex over comment-stripped SQL, not a parser. Misses objects built by dynamic SQL (EXECUTE format).
// Upgrade path: pg_dump --schema-only against the local stack if exact current-state is ever needed.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'supabase', 'migrations');
const out = join(root, 'docs', 'db', 'SCHEMA_SUMMARY.md');
const names = (s) => [...new Set(s)];
const cap = (a, n = 6) => (a.length <= n ? a.join(', ') : `${a.slice(0, n).join(', ')} +${a.length - n}`);
const id = String.raw`(?:"?[\w]+"?\.)?"?([\w]+)"?`;
const grab = (re, sql) => names([...sql.matchAll(re)].map((m) => m[1].toLowerCase()));

const tableFirst = new Map(); // table -> migration number that created it
const tableAlters = new Map();
const fnLast = new Map(); // function -> last migration defining it
const rows = [];

for (const f of readdirSync(dir).filter((x) => x.endsWith('.sql')).sort()) {
  const raw = readFileSync(join(dir, f), 'utf8');
  const num = f.slice(0, f.indexOf('_'));
  const slug = f.slice(num.length + 1, -4);
  const title = (raw.match(/^--\s*(.+)$/m)?.[1] ?? '').slice(0, 110);
  const sql = raw.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--.*$/gm, '');
  const created = grab(new RegExp(String.raw`create\s+table\s+(?:if\s+not\s+exists\s+)?${id}`, 'gi'), sql);
  const alteredAll = grab(new RegExp(String.raw`alter\s+table\s+(?:only\s+)?(?:if\s+exists\s+)?${id}`, 'gi'), sql);
  const altered = alteredAll.filter((t) => !created.includes(t));
  const fns = grab(new RegExp(String.raw`create\s+(?:or\s+replace\s+)?function\s+${id}`, 'gi'), sql);
  const policies = grab(/create\s+policy\s+"?([^"\s]+)"?/gi, sql);
  const triggers = grab(/create\s+(?:or\s+replace\s+)?trigger\s+"?([\w]+)"?/gi, sql);
  const drops = grab(new RegExp(String.raw`drop\s+(?:table|function)\s+(?:if\s+exists\s+)?${id}`, 'gi'), sql);
  const revokes = (sql.match(/\brevoke\b/gi) ?? []).length;
  const grants = (sql.match(/\bgrant\b/gi) ?? []).length;
  const definer = /security\s+definer/i.test(sql);
  for (const t of created) if (!tableFirst.has(t)) tableFirst.set(t, num);
  for (const t of altered) tableAlters.set(t, (tableAlters.get(t) ?? 0) + 1);
  for (const fn of fns) fnLast.set(fn, num);
  const parts = [
    created.length && `new tables: ${cap(created)}`,
    altered.length && `alters: ${cap(altered)}`,
    fns.length && `functions: ${cap(fns)}${definer ? ' (definer)' : ''}`,
    policies.length && `policies: ${policies.length}`,
    triggers.length && `triggers: ${cap(triggers)}`,
    drops.length && `drops: ${cap(drops)}`,
    (revokes || grants) && `grants/revokes: ${grants}/${revokes}`,
  ].filter(Boolean);
  rows.push(`- \`${num}\` ${slug}${title ? ` — ${title}` : ''}${parts.length ? `\n  ${parts.join(' · ')}` : ''}`);
}

const tables = [...tableFirst].sort(([a], [b]) => a.localeCompare(b))
  .map(([t, n]) => `- \`${t}\` created ${n}${tableAlters.get(t) ? `, altered in ${tableAlters.get(t)} later migration(s)` : ''}`);
const fnList = [...fnLast].sort(([a], [b]) => a.localeCompare(b)).map(([fn, n]) => `\`${fn}\`@${n}`);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, [
  '# DB schema summary (generated)',
  '',
  `_Generated by \`scripts/db/schema-summary.mjs\` from ${rows.length} migrations in \`supabase/migrations/\`. Do not edit; run \`node scripts/db/schema-summary.mjs\`._`,
  '_Regex-derived: a map for finding the right migration, NOT the truth. Grants and RLS: verify with `has_table_privilege` / `pg_policies` on the local stack (Hard Rule 11), never from this file._',
  '',
  `## Tables (${tables.length}) and where each was created`,
  ...tables,
  '',
  `## Functions (${fnList.length}), \`name@last-defining-migration\``,
  fnList.join(' · '),
  '',
  `## Migrations (${rows.length}), oldest first`,
  ...rows,
  '',
].join('\n'));
console.log(`wrote ${out}: ${rows.length} migrations, ${tables.length} tables, ${fnList.length} functions`);
